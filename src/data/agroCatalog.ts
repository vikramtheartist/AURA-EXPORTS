/**
 * Quick access lookup helper
 */
export function getProductBySlug(slug: string): CatalogProduct | undefined {
  return masterCatalogProducts.find((p) => p.slug === slug || p.id === slug);
}

/**
 * Filter products by subcategory
 */
export function getProductsBySubcategory(subcategoryId: string): CatalogProduct[] {
  return masterCatalogProducts.filter((p) => p.subcategoryId === subcategoryId);
}

/**
 * Get featured agro products for landing page grids
 */
export function getFeaturedAgroProducts(): CatalogProduct[] {
  return masterCatalogProducts.filter((p) => p.featured);
}
